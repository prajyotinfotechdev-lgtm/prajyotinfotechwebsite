/**
 * Resolves the closest matching scene index in targetLang when a user switches
 * between English and Hindi mid-tutorial so they never lose their tutorial step.
 */
export function resolveCrossLanguageSceneIndex(visualKey, targetLang) {
  const scenes = TUTORIAL_LANGUAGES[targetLang]?.scenes || [];
  const exactIdx = scenes.findIndex((s) => s.visualKey === visualKey);
  if (exactIdx !== -1) return exactIdx;

  // English has an extra early `email-prep` step; in Hindi that topic lives in `pro-tips`.
  if (visualKey === "email-prep") {
    const fallbackIdx = scenes.findIndex((s) => s.visualKey === "pro-tips");
    if (fallbackIdx !== -1) return fallbackIdx;
  }
  return 0;
}
